export function scaleFoodToLoggedItem(
  food: NutritionFoodItem,
  slot: NutritionMealSlot,
  servings: number,
  id: string,
): LoggedFoodItem {
  const safeServings = Math.max(0.25, Math.min(10, Math.round(servings * 4) / 4));
  return {
    id,
    foodId: food.id,
    name: food.name,
    slot,
    servingLabel: food.servingLabel,
    servings: safeServings,
    estimatedCalories: Math.round(food.estimatedCalories * safeServings),
    estimatedProteinG: Math.round(food.estimatedProteinG * safeServings * 10) / 10,
    estimatedCarbsG: Math.round(food.estimatedCarbsG * safeServings * 10) / 10,
    estimatedFatG: Math.round(food.estimatedFatG * safeServings * 10) / 10,
    isEstimated: true,
  };
}

export function computeNutritionTotals(items: LoggedFoodItem[]): {
  calories: number;
  proteinG: number;
  carbsG: number;
  fatG: number;
} {
  return items.reduce(
    (acc, item) => ({
      calories: Math.round(acc.calories + item.estimatedCalories),
      proteinG: Math.round((acc.proteinG + item.estimatedProteinG) * 10) / 10,
      carbsG: Math.round((acc.carbsG + item.estimatedCarbsG) * 10) / 10,
      fatG: Math.round((acc.fatG + item.estimatedFatG) * 10) / 10,
    }),
    { calories: 0, proteinG: 0, carbsG: 0, fatG: 0 },
  );
}
